# 복습 개편으로 늘어나는 플레이 시간 어림(겐보, 26.11.28). 안 2판 칸: 1·3·7·30일 → 익힘 → 90일 한 번 더. 다시 틀리면 1일.
import itertools
T_OK=6.0        # 맞힘 한 장: 보고 치기 약 4.5초 + 정답 뒤 1.5초 대기
T_BAD=16.0      # 틀림 한 장: 치기 + 공개 읽기(3~6초) + 따라 치기
T_R2=2*T_OK     # 그 판 2회독: 틀린 카드는 2연속 정답으로 통과(최소 두 번 더)
def card_time(p): return p*T_OK+(1-p)*(T_BAD+T_R2)
def attempts(p):
    # p: [1일,3일,7일,30일] 칸 맞힘 확률. 익힘까지 기대 시도 수와 기대 시간(다시 틀리면 1일로).
    n=len(p)
    # E_i = 1 + p_i E_{i+1} + (1-p_i) E_0,  E_n = 0  → E_i = a_i + b_i E_0
    a=[0.0]*(n+1); b=[0.0]*(n+1)
    ta=[0.0]*(n+1); tb=[0.0]*(n+1)
    for i in range(n-1,-1,-1):
        a[i]=1+p[i]*a[i+1]; b[i]=p[i]*b[i+1]+(1-p[i])
        ta[i]=card_time(p[i])+p[i]*ta[i+1]; tb[i]=p[i]*tb[i+1]+(1-p[i])
    E0=a[0]/(1-b[0]); T0=ta[0]/(1-tb[0])
    return E0,T0
def per_wrong(p,p90):
    E,T=attempts(p)
    E1,T1=attempts(p)
    # 90일 점검 한 번: 맞히면 끝, 틀리면 사슬을 처음부터 한 번 더(그 뒤 90일은 셈에서 뺌)
    return E+1+(1-p90)*E1, T+card_time(p90)+(1-p90)*T1
scen={'낙관(복습 때 85%)':([.85,.85,.85,.85],.85),'중간(75%)':([.75,.75,.75,.70],.75),'비관(60%)':([.60,.65,.65,.55],.60)}
print('| 처음 오답률 | 기억 가정 | 틀린 카드 1장당 복습 시도 | 지금 12장 판 | 늘어나는 복습 시간(판당) | 늘어나는 비율 |')
print('|---|---|---|---|---|---|')
for e in [.1,.2,.3,.4]:
    base=12*card_time(1-e)
    for k,(p,p90) in scen.items():
        E,T=per_wrong(p,p90)
        add=12*e*T
        print(f'| {int(e*100)}% | {k} | {E:.1f}번 | {base/60:.1f}분 | +{add/60:.1f}분 | +{add/base*100:.0f}% |')
